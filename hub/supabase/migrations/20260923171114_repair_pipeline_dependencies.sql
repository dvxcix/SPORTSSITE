create table if not exists public.creator_scheduled_posts (
  id uuid primary key default gen_random_uuid(),
  creator_id uuid not null references public.users(id) on delete cascade,
  content text not null check (char_length(btrim(content)) between 1 and 500),
  post_type text not null default 'text' check (post_type in ('text', 'analysis')),
  sport text null check (sport is null or sport in ('MLB', 'NFL', 'NBA', 'NHL', 'NCAAF', 'NCAAB')),
  visibility text not null default 'public' check (visibility in ('public', 'followers', 'premium')),
  media_urls text[] not null default '{}',
  scheduled_for timestamptz not null,
  status text not null default 'scheduled' check (status in ('draft', 'scheduled', 'publishing', 'published', 'canceled', 'failed')),
  published_post_id uuid null references public.posts(id) on delete set null,
  attempts integer not null default 0 check (attempts between 0 and 5),
  last_error text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists creator_scheduled_posts_due_idx on public.creator_scheduled_posts (scheduled_for)
  where status = 'scheduled';
create index if not exists creator_scheduled_posts_creator_idx on public.creator_scheduled_posts (creator_id, scheduled_for desc);

alter table public.creator_scheduled_posts enable row level security;
drop policy if exists "Creators read own scheduled posts" on public.creator_scheduled_posts;
drop policy if exists "Creators create own scheduled posts" on public.creator_scheduled_posts;
drop policy if exists "Creators update own unpublished posts" on public.creator_scheduled_posts;
drop policy if exists "Creators delete own unpublished posts" on public.creator_scheduled_posts;
create policy "Creators read own scheduled posts" on public.creator_scheduled_posts for select using (creator_id = (select auth.uid()));
create policy "Creators create own scheduled posts" on public.creator_scheduled_posts for insert with check (creator_id = (select auth.uid()));
create policy "Creators update own unpublished posts" on public.creator_scheduled_posts for update
  using (creator_id = (select auth.uid()) and status in ('draft', 'scheduled', 'failed'))
  with check (creator_id = (select auth.uid()));
create policy "Creators delete own unpublished posts" on public.creator_scheduled_posts for delete
  using (creator_id = (select auth.uid()) and status in ('draft', 'scheduled', 'failed', 'canceled'));
grant select, insert, update, delete on public.creator_scheduled_posts to authenticated;

create or replace function public.set_creator_scheduled_post_updated_at()
returns trigger language plpgsql security invoker set search_path = public as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists set_creator_scheduled_post_updated_at on public.creator_scheduled_posts;
create trigger set_creator_scheduled_post_updated_at before update on public.creator_scheduled_posts
for each row execute function public.set_creator_scheduled_post_updated_at();


create table if not exists public.product_interaction_events (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete set null,
  session_id uuid not null,
  event_name text not null check (event_name in ('route_view', 'route_ready', 'action_success', 'action_failure', 'slow_interaction', 'activation')),
  route text not null check (route ~ '^/[A-Za-z0-9_./@%{}\[\]-]*$' and length(route) between 1 and 180),
  outcome text not null default 'observed' check (outcome in ('observed', 'success', 'failure', 'abandoned')),
  duration_ms integer check (duration_ms is null or duration_ms between 0 and 120000),
  device_class text not null check (device_class in ('phone', 'foldable', 'tablet', 'desktop', 'wide')),
  created_at timestamptz not null default now()
);

create index if not exists product_interaction_events_recent_idx
  on public.product_interaction_events(created_at desc);
create index if not exists product_interaction_events_route_recent_idx
  on public.product_interaction_events(route, created_at desc);
create index if not exists product_interaction_events_failure_recent_idx
  on public.product_interaction_events(event_name, created_at desc)
  where outcome = 'failure' or event_name = 'slow_interaction';

alter table public.product_interaction_events enable row level security;

drop policy if exists "Admins read product interaction telemetry" on public.product_interaction_events;
create policy "Admins read product interaction telemetry"
on public.product_interaction_events for select to authenticated
using (
  exists (
    select 1 from public.users member
    where member.id = (select auth.uid()) and member.account_type = 'admin'
  )
);

revoke all on public.product_interaction_events from public, anon, authenticated;
grant select on public.product_interaction_events to authenticated;

create or replace function public.record_product_interaction(
  p_session_id uuid,
  p_event_name text,
  p_route text,
  p_outcome text,
  p_duration_ms integer,
  p_device_class text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_now timestamptz := now();
  v_count integer;
  v_rate_key text := 'product-telemetry:' || p_session_id::text;
begin
  if p_event_name not in ('route_view', 'route_ready', 'action_success', 'action_failure', 'slow_interaction', 'activation') then return false; end if;
  if p_outcome not in ('observed', 'success', 'failure', 'abandoned') then return false; end if;
  if p_device_class not in ('phone', 'foldable', 'tablet', 'desktop', 'wide') then return false; end if;
  if p_route is null or length(p_route) not between 1 and 180 or p_route !~ '^/[A-Za-z0-9_./@%{}\[\]-]*$' then return false; end if;
  if p_duration_ms is not null and p_duration_ms not between 0 and 120000 then return false; end if;

  insert into public.rate_limit_counters as counters (key, window_start, count)
  values (v_rate_key, v_now, 1)
  on conflict (key) do update set
    window_start = case when counters.window_start < v_now - interval '1 day' then v_now else counters.window_start end,
    count = case when counters.window_start < v_now - interval '1 day' then 1 else least(counters.count + 1, 121) end
  returning count into v_count;
  if v_count > 120 then return false; end if;

  insert into public.product_interaction_events(user_id, session_id, event_name, route, outcome, duration_ms, device_class)
  values (auth.uid(), p_session_id, p_event_name, p_route, p_outcome, p_duration_ms, p_device_class);
  return true;
end;
$$;

revoke all on function public.record_product_interaction(uuid, text, text, text, integer, text) from public;
grant execute on function public.record_product_interaction(uuid, text, text, text, integer, text) to anon, authenticated;


